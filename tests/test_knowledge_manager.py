class TestDiscoverDocFiles(unittest.TestCase):
    def setUp(self):
        self.tmpdir = tempfile.mkdtemp()
        self.sourcedir = tempfile.mkdtemp()
        self.mgr = KnowledgeManager(self.tmpdir)
        # Create some doc files
        with open(os.path.join(self.sourcedir, "README.md"), "w") as f:
            f.write("# Test")
        os.makedirs(os.path.join(self.sourcedir, "docs"))
        with open(os.path.join(self.sourcedir, "docs", "design.md"), "w") as f:
            f.write("# Design")
        # Create non-doc file
        with open(os.path.join(self.sourcedir, "main.c"), "w") as f:
            f.write("int main() {}")

    def tearDown(self):
        import shutil
        shutil.rmtree(self.tmpdir, ignore_errors=True)
        shutil.rmtree(self.sourcedir, ignore_errors=True)

    def test_discovers_docs(self):
        docs = self.mgr._discover_doc_files(self.sourcedir)
        names = [os.path.basename(d) for d in docs]
        self.assertIn("README.md", names)
        self.assertIn("design.md", names)

    def test_skips_source_files(self):
        docs = self.mgr._discover_doc_files(self.sourcedir)
        names = [os.path.basename(d) for d in docs]
        self.assertNotIn("main.c", names)


